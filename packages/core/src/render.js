export const SPECIMEN_SUBJECT = 'synthetic specimen, not a real document';
export const BAND_TEXT = 'SYNTHETIC SPECIMEN - generated by claimseed for software testing - not a real document';
export const WATERMARK_TEXT = 'CLAIMSEED SPECIMEN';
// The watermark is drawn as filled rectangles (a 5x7 block-letter font), not as text: a diagonal text watermark
// interleaves its letters into `pdftotext -layout` output ("S P EC I M EN" across body lines), which would corrupt the
// very extraction tests claimseed exists to feed. The band at the foot of every page carries the extractable text.
const BLOCK_FONT = {
  C: ['01110', '10001', '10000', '10000', '10000', '10001', '01110'], L: ['10000', '10000', '10000', '10000', '10000', '10000', '11111'],
  A: ['01110', '10001', '10001', '11111', '10001', '10001', '10001'], I: ['11111', '00100', '00100', '00100', '00100', '00100', '11111'],
  M: ['10001', '11011', '10101', '10101', '10001', '10001', '10001'], S: ['01111', '10000', '10000', '01110', '00001', '00001', '11110'],
  E: ['11111', '10000', '10000', '11110', '10000', '10000', '11111'], D: ['11110', '10001', '10001', '10001', '10001', '10001', '11110'],
  P: ['11110', '10001', '10001', '11110', '10000', '10000', '10000'], N: ['10001', '11001', '10101', '10011', '10001', '10001', '10001'],
  ' ': ['00000', '00000', '00000', '00000', '00000', '00000', '00000'],
};
export const WATERMARK_COLOR = rgb(0.72, 0.325, 0.118);
function drawBlockText(page, text, { x, y, cell, angleDeg, color, opacity }) {
  const a = (angleDeg * Math.PI) / 180; const cos = Math.cos(a); const sin = Math.sin(a);
  let col = 0;
  for (const ch of text) {
    const rows = BLOCK_FONT[ch] || BLOCK_FONT[' '];
    for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) {
      if (rows[r][c] !== '1') continue;
      const lx = (col + c) * cell; const ly = (6 - r) * cell;   // position in the unrotated text frame
      page.drawRectangle({ x: x + lx * cos - ly * sin, y: y + lx * sin + ly * cos, width: cell, height: cell, rotate: degrees(angleDeg), color, opacity, borderWidth: 0 });
    }
    col += 6;
  }
}
// A number tree (the structure tree's ParentTree) entry, or undefined. Cycles and malformed nodes end the search.
function numberTreeGet(context, node, key, seen = new Set()) {
  const d = context.lookup(node);
  if (!(d instanceof PDFDict) || seen.has(d) || seen.size > 4096) return undefined;
  seen.add(d);
  const nums = d.lookup(PDFName.of('Nums'));
  if (nums instanceof PDFArray) for (let j = 0; j + 1 < nums.size(); j += 2) { const k = nums.lookup(j); if (k instanceof PDFNumber && k.asNumber() === key) return nums.lookup(j + 1); }
  const kids = d.lookup(PDFName.of('Kids'));
  if (kids instanceof PDFArray) for (let j = 0; j < kids.size(); j++) { const r = numberTreeGet(context, kids.get(j), key, seen); if (r !== undefined) return r; }
  return undefined;
}

// In a tagged PDF the structure tree finds a page's marked content by MCID in the page's content stream. Once that
// content is a Form XObject, each of those MCIDs is addressed through a marked-content reference naming the Form
// XObject (Stm), and the Form XObject takes over the page's ParentTree key, so the structure (and the text a
// structure-aware reader extracts through it) still resolves.
function moveStructureToForm(doc, page, form, formRef) {
  const key = page.node.get(PDFName.of('StructParents'));
  const root = doc.catalog.lookup(PDFName.of('StructTreeRoot'));
  if (!(key instanceof PDFNumber) || !(root instanceof PDFDict)) return;
  form.dict.set(PDFName.of('StructParents'), key); page.node.delete(PDFName.of('StructParents'));
  const parents = numberTreeGet(doc.context, root.get(PDFName.of('ParentTree')), key.asNumber());
  if (!(parents instanceof PDFArray)) return;
  const [MCR, Type, Pg, Stm, MCID, K] = ['MCR', 'Type', 'Pg', 'Stm', 'MCID', 'K'].map((s) => PDFName.of(s));
  for (let mcid = 0; mcid < parents.size(); mcid++) {
    const el = parents.lookup(mcid);
    if (!(el instanceof PDFDict)) continue;
    const elPage = el.get(Pg);
    const fix = (item) => {   // the replacement for one content item of el, or undefined to keep it
      if (item instanceof PDFNumber) return item.asNumber() === mcid && (elPage === undefined || elPage === page.ref) ? doc.context.obj({ Type: 'MCR', Pg: page.ref, Stm: formRef, MCID: mcid }) : undefined;
      const d = doc.context.lookup(item);
      const id = d instanceof PDFDict && d.lookup(MCID);
      if (d instanceof PDFDict && d.lookup(Type) === MCR && !d.has(Stm) && id instanceof PDFNumber && id.asNumber() === mcid && (d.get(Pg) || elPage) === page.ref) d.set(Stm, formRef);
      return undefined;
    };
    const kids = el.lookup(K);
    if (kids instanceof PDFArray) { for (let j = 0; j < kids.size(); j++) { const r = fix(kids.get(j)); if (r) kids.set(j, r); } }
    else if (kids !== undefined) { const r = fix(el.get(K)); if (r) el.set(K, r); }
  }
}

// Move the page's own content into one Form XObject and leave the page drawing only that Form XObject (the markers
// are drawn after it). The Form XObject holds exactly the bytes assertBalancedContent checked, so a viewer runs the
// content that was checked, with no stream boundaries left to read differently, and with the page's own resources.
// A viewer saves the graphics state before it draws a Form XObject and restores it afterwards, whatever the content
// does inside, so nothing the content sets (a clip, a transform, a soft mask, a text state, an unbalanced q or Q) can
// reach the markers even through a construct a viewer and the content check might read differently; poppler, PDFium
// and Chrome also end an open marked-content sequence with the Form XObject. Its BBox is the MediaBox and its
// matrix is the identity, so it draws exactly where the content drew. Returns the replaced content stream references.
function isolatePageContent(doc, page, bytes) {
  const { context } = doc; const node = page.node;
  const old = node.get(PDFName.of('Contents'));
  const oldRefs = old instanceof PDFRef ? [old] : old instanceof PDFArray ? old.asArray().filter((r) => r instanceof PDFRef) : [];
  const mb = page.getMediaBox();
  const bbox = [Math.min(mb.x, mb.x + mb.width), Math.min(mb.y, mb.y + mb.height), Math.max(mb.x, mb.x + mb.width), Math.max(mb.y, mb.y + mb.height)];
  const resources = node.getInheritableAttribute(PDFName.of('Resources'));
  const form = context.flateStream(bytes, { Type: 'XObject', Subtype: 'Form', BBox: bbox, Resources: resources || {} });
  const formRef = context.register(form);
  moveStructureToForm(doc, page, form, formRef);
  // the page gets resources of its own (the Form XObject, and the font and graphics states the markers add), so the
  // original resources, which other pages may share, are left as they were
  node.set(PDFName.of('Resources'), context.obj({ XObject: { PageContent: formRef } }));
  node.set(PDFName.of('Contents'), context.register(context.flateStream('/PageContent Do\n')));
  return oldRefs;
}

// Remove the replaced content streams that nothing in the document refers to any more (a stream can also be used
// elsewhere, for instance as a Form XObject, and is then kept).
function dropUnreferenced(context, candidates) {
  if (!candidates.size) return;
  const used = new Set();
  const visit = (o) => {
    if (o instanceof PDFRef) { if (candidates.has(o)) used.add(o); return; }
    if (o instanceof PDFStream) visit(o.dict);
    else if (o instanceof PDFDict) for (const [, v] of o.entries()) visit(v);
    else if (o instanceof PDFArray) for (const v of o.asArray()) visit(v);
  };
  for (const [, obj] of context.enumerateIndirectObjects()) visit(obj);
  for (const v of Object.values(context.trailerInfo)) visit(v);
  for (const r of candidates) if (!used.has(r)) context.delete(r);
}

// Draw the specimen band (text) and the diagonal watermark (block rectangles) on every page with pdf-lib, after
// rendering. This does not depend on the HTML, the templates or any CSS, so no data object or template mistake can
// remove it; the band text is the PDF-standard Helvetica (not embedded, so bytes stay deterministic) in fixed colours.
async function stampPages(doc, bandSuffix) {
  // document-level actions and scripts (OpenAction, additional actions, JavaScript name tree) and the form dictionary
  // go too: a viewer could otherwise run code that hides or covers the markers when the document opens
  const cat = doc.catalog; for (const k of ['OpenAction', 'AA', 'AcroForm']) cat.delete(PDFName.of(k));
  const names = cat.lookup(PDFName.of('Names')); if (names && typeof names.delete === 'function') names.delete(PDFName.of('JavaScript'));
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const band = bandSuffix ? `${BAND_TEXT} - ${bandSuffix}` : BAND_TEXT;
  const pages = doc.getPages();
  // Every page's own content must be readable unambiguously, restore the graphics state it changes and end the
  // marked-content sequences it begins before anything is drawn (see pdf-content.js); the checked bytes are what the
  // page draws from here on
  const contents = pages.map((page, i) => assertBalancedContent(doc, page, i));
  const replaced = new Set();
  for (const [index, page] of pages.entries()) {
    // The markers are drawn in the page's own coordinate space: a caller's PDF may carry an offset MediaBox, a
    // CropBox smaller than the MediaBox, or annotations that would cover the foot of the page. The band and the
    // watermark go inside the visible box, annotations are dropped, and a page too small to carry a legible band
    // (under 3 in on a side) is refused.
    // The visible page is the CropBox clipped to the MediaBox (a viewer shows only their intersection): the markers are
    // placed in that intersection, and an empty, non-finite or undersized one is refused.
    const norm = (r) => { const x1 = Math.min(r.x, r.x + r.width), x2 = Math.max(r.x, r.x + r.width), y1 = Math.min(r.y, r.y + r.height), y2 = Math.max(r.y, r.y + r.height); return { x1, x2, y1, y2 }; };
    const mb = norm(page.getMediaBox()); const cb = norm(page.getCropBox() || page.getMediaBox());
    const vis = { x1: Math.max(mb.x1, cb.x1), x2: Math.min(mb.x2, cb.x2), y1: Math.max(mb.y1, cb.y1), y2: Math.min(mb.y2, cb.y2) };
    if (![vis.x1, vis.x2, vis.y1, vis.y2].every(Number.isFinite)) throw new Error('stamp refused: page box is not a finite rectangle');
    const ox = vis.x1, oy = vis.y1, width = vis.x2 - vis.x1, height = vis.y2 - vis.y1;
    if (!(width >= 216 && height >= 216)) throw new Error(`stamp refused: visible page ${Math.max(0, width).toFixed(0)}x${Math.max(0, height).toFixed(0)} pt is too small to carry the specimen band (3 in minimum)`);
    page.node.delete(PDFName.of('Annots')); page.node.delete(PDFName.of('AA'));   // annotations (and so form widgets) and page actions: nothing may be drawn over the markers or run when the page opens
    if (contents[index].length) for (const r of isolatePageContent(doc, page, contents[index])) replaced.add(r);
    page.drawRectangle({ x: ox, y: oy, width, height: 11, color: rgb(0.984, 0.953, 0.918), borderColor: rgb(0.89, 0.788, 0.659), borderWidth: 0.5 });
    // the band always fits the page: on a page narrower than the band at 6.5 pt (a caller's small page through
    // mergePdfs/finalizePdf), the fixed text is kept whole and the suffix is dropped first, then the size shrinks
    let size = 6.5; let text = band;
    if (font.widthOfTextAtSize(text, size) > width - 8) text = BAND_TEXT;
    if (font.widthOfTextAtSize(text, size) > width - 8) size = Math.max(3, (width - 8) / font.widthOfTextAtSize(text, 1));
    const tw = font.widthOfTextAtSize(text, size);
    page.drawText(text, { x: ox + Math.max(4, (width - tw) / 2), y: oy + 3, size, font, color: rgb(0.42, 0.29, 0.17) });
    // 18 columns x 6 cells wide at `cell` points; centred on the page, rotated 28 degrees, sized so the rotated run
    // fits inside the page with a margin on either side
    const a = (28 * Math.PI) / 180; const cols = WATERMARK_TEXT.length * 6 - 1;
    const cell = Math.min(Math.min(width, height) / 100, (width - 36) / (cols * Math.cos(a) + 7 * Math.sin(a)));
    const textW = cols * cell; const textH = 7 * cell; const cx = ox + width / 2; const cy = oy + height / 2;
    const x0 = cx - (textW / 2) * Math.cos(a) + (textH / 2) * Math.sin(a); const y0 = cy - (textW / 2) * Math.sin(a) - (textH / 2) * Math.cos(a);
    drawBlockText(page, WATERMARK_TEXT, { x: x0, y: y0, cell, angleDeg: 28, color: WATERMARK_COLOR, opacity: 0.14 });
  }
  dropUnreferenced(doc.context, replaced);
}
function setSpecimenMetadata(doc, meta) {
  doc.setProducer('claimseed'); doc.setCreator('claimseed'); doc.setSubject(SPECIMEN_SUBJECT);
  doc.setTitle(meta.title || 'claimseed synthetic specimen'); doc.setKeywords(['synthetic', 'specimen', 'claimseed', 'test-data']);
  const fixed = new Date('2026-01-01T00:00:00Z'); doc.setCreationDate(fixed); doc.setModificationDate(fixed);
}
// Stamp a finished PDF in place and set the specimen metadata. Every render function in this package produces its
// output through mergePdfs, which stamps; finalizePdf is for callers that assembled a PDF through renderHtmlToPdf
// themselves. It always stamps (calling it on an already-stamped PDF draws the markers twice).
export async function finalizePdf(pdfPath, meta = {}) {
  const doc = await PDFDocument.load(fs.readFileSync(pdfPath), { updateMetadata: false });
  await stampPages(doc, meta.band);
  setSpecimenMetadata(doc, meta);
  fs.writeFileSync(pdfPath, await doc.save());
  return pdfPath;
}
// Merge page PDFs, stamp every page and set the specimen metadata. This is the single exit point of every render
// function (renderMsn, renderItemizedBill, renderPpoEob, renderHmoEob), through the CLI or the library API, so no
// claimseed document leaves unstamped. meta.band adds context (type / scenario / seed) to the band text;
// meta.expectedPages is the page count the paginator planned and printed in "Page X of N" — a mismatch (an
// overflowing page) is an error, never a silently wrong document.
export async function mergePdfs(pdfPaths, outputPath, meta = {}) {
  const merged = await PDFDocument.create({ updateMetadata: false });
  setSpecimenMetadata(merged, meta);

  for (const pdfPath of pdfPaths) {
    const bytes = fs.readFileSync(pdfPath);
    const doc = await PDFDocument.load(bytes);
    const copiedPages = await merged.copyPages(doc, doc.getPageIndices());
    for (const page of copiedPages) {
      merged.addPage(page);
    }
  }

  if (meta.expectedPages != null && merged.getPageCount() !== meta.expectedPages)
    throw new Error(`pagination mismatch: planned ${meta.expectedPages} pages, rendered ${merged.getPageCount()} (a page overflowed)`);
  await stampPages(merged, meta.band);
  const mergedBytes = await merged.save();
  fs.writeFileSync(outputPath, mergedBytes);
  console.log(`  Merged ${pdfPaths.length} PDFs -> ${path.basename(outputPath)}`);
  return outputPath;
}

// Public single-document render: harden, print, then stamp the specimen markers and metadata. Every PDF a library
// caller can obtain from this package is stamped: this function, the render functions (through mergePdfs) and
// render() in index.js. The unstamped page printer is internal (src/print.js, outside the exports map).
export async function renderHtmlToPdf(browser, html, outputPath, options = {}) {
  const meta = stampMeta(options);   // read the options before anything is printed (a throwing getter fails here, with nothing written)
  const work = fs.mkdtempSync(path.join(os.tmpdir(), 'claimseed-page-'));
  try {
    const tmp = path.join(work, 'page.pdf');
    await printPage(browser, hardenHtml(html), tmp, options);
    await finalizePdf(tmp, meta);
    fs.copyFileSync(tmp, outputPath);   // only stamped bytes ever reach the caller's path
    return outputPath;
  } finally { fs.rmSync(work, { recursive: true, force: true }); }
}

// Render options every render function accepts as its fourth argument: { band, title } (strings printed in the
// specimen band / PDF title; the CLI passes type, scenario and seed). Anything else is ignored.
// The band is drawn with the PDF-standard Helvetica (WinAnsi), so any character outside Latin-1 printable range is
// replaced by '?' here rather than throwing inside stampPages after pages have been rendered.
const winAnsi = (t) => t.replace(/[^\x20-\x7E\xA0-\xFF]/g, '?');
export function stampMeta(opts = {}) {
  return { band: typeof opts.band === 'string' ? winAnsi(opts.band).slice(0, 120) : undefined, title: typeof opts.title === 'string' ? opts.title.slice(0, 200) : undefined };
}

// ============================================================
// MSN claim pagination engine
// ============================================================
// MSN Part B uses LANDSCAPE pages for claims. Claims start on page 3.
// If claims overflow page 3, they continue on additional pages.
// The first claims page includes the title, intro, and definitions.

function paginateClaimsForMsn(data) {
  const claims = data.claims || [];
  const notes = data.notes || [];

  // Landscape page capacity in "units" — shorter height (8.5in) but wider
  // Reserve space for per-page notes section at bottom (~4-6 notes per page)
  const PAGE_CAPACITY_FULL = 26;
  const NOTES_RESERVE = 4.0; // reserve space for notes at bottom of every claims page
  const PAGE_CAPACITY = PAGE_CAPACITY_FULL - NOTES_RESERVE;
  const TITLE_AND_DEFS_COST = 11; // title bar + intro + definitions (first page only)
  const PROVIDER_HEADER_COST = 2.5;
  const DATE_HEADER_COST = 0.8;
  const TABLE_HEADER_COST = 2.0;
  const LINE_ITEM_COST = 1.8; // MSN line items are compact in landscape
  const TOTALS_COST = 1.2;

  // Build a map of note letter -> note object for quick lookup
  const noteMap = {};
  for (const n of notes) {
    noteMap[n.letter] = n;
  }

  const pages = [];
  let currentPage = {
    pageNumber: 3,
    showTitle: true,
    showContinued: false,
    claimBlocks: [],
    showNotes: false,
  };
  let remaining = PAGE_CAPACITY - TITLE_AND_DEFS_COST;

  let lastDate = null;

  for (let ci = 0; ci < claims.length; ci++) {
    const claim = claims[ci];
    const items = claim.lineItems;

    const startCost = PROVIDER_HEADER_COST + TABLE_HEADER_COST;

    // If we can't fit header + first item, start new page. A fresh claim starts here, so the page is NOT a
    // continuation (the 'provider continued...' header is only for a claim split across pages).
    if (remaining < startCost + LINE_ITEM_COST + DATE_HEADER_COST) {
      pages.push(currentPage);
      const nextNum = currentPage.pageNumber + 1;
      currentPage = {
        pageNumber: nextNum,
        showTitle: false,
        showContinued: false,
        claimBlocks: [],
        showNotes: false,
      };
      remaining = PAGE_CAPACITY;
      lastDate = null;
    }

    // Start the claim block
    let block = {
      providerName: claim.providerName,
      providerPhone: claim.providerPhone,
      providerAddress: claim.providerAddress,
      referredBy: claim.referredBy,
      claimNumber: claim.claimNumber,
      showProviderHeader: true,
      showTableHeader: true,
      dateHeader: null,
      lineItems: [],
      showTotals: false,
      continued: false,
      claimTotal: claim.claimTotal,
    };

    remaining -= startCost;

    // Add line items
    for (let li = 0; li < items.length; li++) {
      const item = items[li];

      // Check for date header
      let dateCost = 0;
      if (item.dateOfService !== lastDate) {
        dateCost = DATE_HEADER_COST;
      }

      if (remaining < LINE_ITEM_COST + dateCost) {
        // Mark continued, push block, start new page
        block.continued = true;
        currentPage.claimBlocks.push(block);
        pages.push(currentPage);

        const nextNum = currentPage.pageNumber + 1;
        currentPage = {
          pageNumber: nextNum,
          showTitle: false,
          showContinued: true,
          claimBlocks: [],
          showNotes: false,
        };
        remaining = PAGE_CAPACITY;

        // Continue claim on new page
        block = {
          providerName: claim.providerName,
          providerPhone: claim.providerPhone,
          providerAddress: claim.providerAddress,
          referredBy: claim.referredBy,
          claimNumber: claim.claimNumber,
          showProviderHeader: true,
          showTableHeader: true,
          dateHeader: null,
          lineItems: [],
          showTotals: false,
          continued: false,
          claimTotal: claim.claimTotal,
        };
        remaining -= startCost;
        lastDate = null;

        // Re-check date header
        dateCost = 0;
        if (item.dateOfService !== lastDate) {
          dateCost = DATE_HEADER_COST;
        }
      }

      // Set date header on block if this is first item or new date
      if (li === 0 || item.dateOfService !== lastDate) {
        if (block.lineItems.length === 0) {
          block.dateHeader = item.dateOfService;
        }
        remaining -= dateCost;
      }

      lastDate = item.dateOfService;
      block.lineItems.push(item);
      remaining -= LINE_ITEM_COST;
    }

    // Add totals row
    if (claim.claimTotal) {
      if (remaining < TOTALS_COST) {
        block.continued = true;
        currentPage.claimBlocks.push(block);
        pages.push(currentPage);

        const nextNum = currentPage.pageNumber + 1;
        currentPage = {
          pageNumber: nextNum,
          showTitle: false,
          showContinued: true,
          claimBlocks: [],
          showNotes: false,
        };
        remaining = PAGE_CAPACITY;

        // Carry the last line item over so the totals never sit alone under a bare provider header.
        const carried = block.lineItems.length > 1 ? [block.lineItems.pop()] : [];
        block = {
          providerName: claim.providerName,
          providerPhone: claim.providerPhone,
          providerAddress: claim.providerAddress,
          referredBy: claim.referredBy,
          claimNumber: claim.claimNumber,
          showProviderHeader: true,
          showTableHeader: true,
          dateHeader: carried.length ? carried[0].dateOfService : null,
          lineItems: carried,
          showTotals: true,
          continued: false,
          claimTotal: claim.claimTotal,
        };
        remaining -= PROVIDER_HEADER_COST + TABLE_HEADER_COST + TOTALS_COST + carried.length * (LINE_ITEM_COST + DATE_HEADER_COST);
      } else {
        block.showTotals = true;
        remaining -= TOTALS_COST;
      }
    }

    currentPage.claimBlocks.push(block);
  }

  pages.push(currentPage);

  // Post-process: set page.continued flag and compute per-page notes
  for (const p of pages) {
    const lastBlock = p.claimBlocks[p.claimBlocks.length - 1];
    p.continued = lastBlock ? lastBlock.continued : false;

    // Collect unique note letters from all line items on this page
    const usedLetters = new Set();
    for (const block of p.claimBlocks) {
      for (const item of block.lineItems) {
        if (item.noteLetters) {
          for (const letter of item.noteLetters) {
            usedLetters.add(letter);
          }
        }
      }
    }

    // Build the notes array for this page, preserving original order
    p.pageNotes = notes.filter(n => usedLetters.has(n.letter));
    p.showNotes = p.pageNotes.length > 0;
  }

  return pages;
}


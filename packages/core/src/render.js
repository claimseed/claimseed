// Bundled OFL fonts (from @fontsource packages) — injected into every page via partials/fonts.html as data: URIs.
// Chrome is launched with an empty fontconfig (see browser.js) so a glyph missing from these faces renders as a
// notdef box instead of pulling a system font; templates must therefore stay within the bundled glyph sets. Resolution walks up from this file to the nearest node_modules/@fontsource.
function findFontsource() {
  let dir = __dirname;
  for (let k = 0; k < 6; k++) {
    const cand = path.join(dir, 'node_modules', '@fontsource');
    if (fs.existsSync(cand)) return cand;
    dir = path.dirname(dir);
  }
  return null;
}

export async function renderMsn(data, stock, outputDir, opts = {}) {
  // Page PDFs are printed into a private temporary directory (removed in `finally`, including on errors) and only the
  // finished, stamped document is written into outputDir, so no unstamped partial can be left behind for a caller.
  const work = fs.mkdtempSync(path.join(os.tmpdir(), 'claimseed-pages-'));
  const ownBrowser = !opts.browser;   // a caller-supplied browser (opts.browser) is shared and left open
  const browser = opts.browser || await launchBrowser();
  const partialPdfs = [];
  let appealsPageNum;
  try {
  try {
  // Compute pagination first to determine total page count
  console.log('  Computing pagination...');
  const claimPages = paginateClaimsForMsn(data);
  const lastClaimPage = claimPages[claimPages.length - 1].pageNumber;
  appealsPageNum = lastClaimPage + 1;

  // Set the total page count before rendering any pages
  // Pages: 1 (dashboard) + 2 (tips) + N (claims) + 1 (appeals)
  data.metadata.pageCount = appealsPageNum;

  const templateData = templateContext(data, stock);

  // --- Page 1: Dashboard (portrait) ---
  console.log('  Rendering page 1 (dashboard)...');
  const html1 = nunjucks.render('msn/page1-dashboard.html', templateData);
  const pdf1 = path.join(work, '.p1.pdf');
  await printPage(browser, hardenHtml(html1), pdf1, { landscape: false });
  partialPdfs.push(pdf1);

  // --- Page 2: Tips (portrait) ---
  console.log('  Rendering page 2 (tips)...');
  const html2 = nunjucks.render('msn/page2-tips.html', templateData);
  const pdf2 = path.join(work, '.p2.pdf');
  await printPage(browser, hardenHtml(html2), pdf2, { landscape: false });
  partialPdfs.push(pdf2);

  // --- Page 3+: Claims (LANDSCAPE, may span multiple pages) ---
  console.log('  Rendering claims pages (landscape)...');

  // Log pagination for debugging
  for (const p of claimPages) {
    const blockNames = p.claimBlocks.map(b => {
      const items = b.lineItems.map(i => i.cptCode).join(', ');
      return `${b.claimNumber}[${items}]${b.continued ? ' (cont)' : ''}${b.showTotals ? ' +totals' : ''}`;
    });
    console.log(`    Page ${p.pageNumber}: ${blockNames.join(' | ')}${p.showNotes ? ' | NOTES' : ''}`);
  }

  const htmlClaims = nunjucks.render('msn/page3-claims.html', {
    ...templateData,
    claimPages,
  });
  const pdfClaims = path.join(work, '.p3-claims.pdf');
  await printPage(browser, hardenHtml(htmlClaims), pdfClaims, { landscape: true });
  partialPdfs.push(pdfClaims);

  // --- Appeals page (portrait) ---
  console.log(`  Rendering page ${appealsPageNum} (appeals)...`);
  const htmlAppeals = nunjucks.render('msn/page4-appeals.html', {
    ...templateData,
    appealsPageNumber: appealsPageNum,
  });
  const pdfAppeals = path.join(work, '.p4-appeals.pdf');
  await printPage(browser, hardenHtml(htmlAppeals), pdfAppeals, { landscape: false });
  partialPdfs.push(pdfAppeals);
  } finally { if (ownBrowser) await browser.close(); }

  // Output names are fixed (never derived from data); the CLI / render() name the final file.
  const finalPdf = path.join(outputDir, 'msn.pdf');
  await mergePdfs(partialPdfs, finalPdf, { ...stampMeta(opts), expectedPages: appealsPageNum });
  return finalPdf;
  } finally { fs.rmSync(work, { recursive: true, force: true }); }
}

// ============================================================
// Hospital itemized bill (portrait): revenue-code groups with line items, subtotals and a grand total.
// Groups can split across pages but follow orphan/widow rules.
// ============================================================

function paginateForItemizedBill(data) {
  const groups = data.revenueCodeGroups || [];
  const grandTotal = data.grandTotal;

  // Portrait page capacity in "slots" (one slot = one 13pt table row) after the hospital header and footer.
  const PAGE_CAPACITY = 40;
  const COLUMN_HEADER_COST = 1.5;
  const GROUP_HEADER_COST = 1.5;
  const LINE_ITEM_COST = 1.0;
  const SUBTOTAL_COST = 1.0;
  const GRAND_TOTAL_COST = 1.5;

  const pages = [];
  let currentPage = {
    pageNumber: 2, // page 1 is cover
    showColumnHeaders: true,
    blocks: [],
  };
  let remaining = PAGE_CAPACITY - COLUMN_HEADER_COST;
  let lineItemIndex = 0; // global zebra index

  function startNewPage() {
    pages.push(currentPage);
    const nextNum = currentPage.pageNumber + 1;
    currentPage = {
      pageNumber: nextNum,
      showColumnHeaders: true,
      blocks: [],
    };
    remaining = PAGE_CAPACITY - COLUMN_HEADER_COST;
  }

  for (let gi = 0; gi < groups.length; gi++) {
    const group = groups[gi];
    const items = group.lineItems;
    const groupTotalCost = GROUP_HEADER_COST + items.length * LINE_ITEM_COST + SUBTOTAL_COST;

    // Rule 3: if whole group fits, keep it together
    if (groupTotalCost <= remaining) {
      currentPage.blocks.push({
        type: 'group-header',
        revCode: group.revCode,
        description: group.description,
      });
      remaining -= GROUP_HEADER_COST;

      for (let li = 0; li < items.length; li++) {
        const item = items[li];
        currentPage.blocks.push({
          type: 'line-item',
          date: item.date,
          hcpcs: item.hcpcs,
          units: item.units,
          description: item.description,
          amount: item.amount,
          zebraIndex: lineItemIndex++,
        });
        remaining -= LINE_ITEM_COST;
      }

      currentPage.blocks.push({
        type: 'subtotal',
        amount: group.subtotal,
      });
      remaining -= SUBTOTAL_COST;
      continue;
    }

    // Group doesn't fit entirely — need to split it across pages

    // Rule 1: Never orphan a group header — need header + at least 1 line item
    const minStartCost = GROUP_HEADER_COST + LINE_ITEM_COST;
    if (remaining < minStartCost) {
      startNewPage();
    }

    // Place group header
    currentPage.blocks.push({
      type: 'group-header',
      revCode: group.revCode,
      description: group.description,
    });
    remaining -= GROUP_HEADER_COST;

    // Place line items
    for (let li = 0; li < items.length; li++) {
      const item = items[li];
      const isLastItem = li === items.length - 1;

      // Rule 2: If this is the last item, we need room for item + subtotal
      // to avoid stranding the subtotal alone on next page
      if (isLastItem) {
        const neededForLast = LINE_ITEM_COST + SUBTOTAL_COST;
        if (remaining < neededForLast) {
          startNewPage();
        }
      } else if (remaining < LINE_ITEM_COST) {
        startNewPage();
        // Note: group header NOT repeated on continuation pages (Rule 5)
      }

      currentPage.blocks.push({
        type: 'line-item',
        date: item.date,
        hcpcs: item.hcpcs,
        units: item.units,
        description: item.description,
        amount: item.amount,
        zebraIndex: lineItemIndex++,
      });
      remaining -= LINE_ITEM_COST;
    }

    // Place subtotal
    currentPage.blocks.push({
      type: 'subtotal',
      amount: group.subtotal,
    });
    remaining -= SUBTOTAL_COST;
  }

  // Grand total at end of last charge page
  if (remaining < GRAND_TOTAL_COST) {
    startNewPage();
  }
  currentPage.blocks.push({
    type: 'grand-total',
    amount: grandTotal,
  });

  // Push final page
  pages.push(currentPage);

  return pages;
}

